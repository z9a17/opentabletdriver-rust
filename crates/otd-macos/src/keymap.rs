/// Aggregate CoreGraphics modifier flags for independently held left/right keys.
pub fn modifier_flags(held: u8) -> u64 {
    let mut flags = 0;
    for (mask, flag) in [(0x11, 1 << 18), (0x22, 1 << 17), (0x44, 1 << 19), (0x88, 1 << 20)] {
        if held & mask != 0 { flags |= flag; }
    }
    flags
}
